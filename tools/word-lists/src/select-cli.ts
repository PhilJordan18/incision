/**
 * `npm run select:data -w @incision/word-lists -- --raw-dir <raw> --version <version>`
 *
 * Rebuilds the server-only word data of `@incision/domain/words` from the pinned wordfreq files and
 * the committed register `review/<version>/`, then writes `review/<version>/manifest.json` with
 * every input and output digest. Re-running it on the same inputs rewrites the same bytes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readCbPack } from "./cbpack";
import { serializeCandidate, sha256, verifiedCreditsDigest } from "./candidate";
import { readPinned } from "./pinned";
import { parseExtraPairs, parseReview, selectPlayable, SELECTION_POLICY, type Language, type Selection } from "./select";

const LANGUAGES: readonly Language[] = ["fr", "en"];
const DATA_DIR = new URL("../../../packages/domain/src/words/data/", import.meta.url);
const HEADER = "// Generated by tools/word-lists (npm run select:data) from the reviewed register; do not edit.\n// Sources, licences and review: notice.ts and tools/word-lists/review/.\n";

const constant = (name: string, source: string): string => `export const ${name} = \`${source}\`;\n`;

function run(rawDir: string, version: string): void {
  const reviewDir = new URL(`../review/${version}/`, import.meta.url);
  const credits = readFileSync(new URL("../notices/wordfreq-3.1.1.md", import.meta.url), "utf8");
  const selections = new Map<Language, Selection>();
  const inputs: Record<string, string> = { "notices/wordfreq-3.1.1.md": verifiedCreditsDigest(credits) };
  for (const language of LANGUAGES) {
    const path = `wordfreq-3.1.1/wordfreq/data/large_${language}.msgpack.gz`;
    const raw = readPinned(rawDir, path);
    inputs[path] = sha256(raw);
    const review = readFileSync(new URL(`${language}.review.tsv`, reviewDir), "utf8");
    const pairs = readFileSync(new URL(`${language}.pairs.tsv`, reviewDir), "utf8");
    inputs[`review/${version}/${language}.review.tsv`] = sha256(review);
    inputs[`review/${version}/${language}.pairs.tsv`] = sha256(pairs);
    const { source } = serializeCandidate(readCbPack(raw), language, "candidate-1");
    inputs[`candidate ${language} (exporter policy 1)`] = sha256(source);
    selections.set(language, selectPlayable({ candidate: source, review: parseReview(review, language), extraPairs: parseExtraPairs(pairs, language), version }));
  }
  const fr = selections.get("fr");
  const en = selections.get("en");
  if (fr === undefined || en === undefined) throw new Error("Both languages are required");
  const files: Record<string, string> = {
    "fr.ts": HEADER + constant("FR_WORDS", fr.words),
    "en.ts": HEADER + constant("EN_WORDS", en.words),
    "exclusions.ts": HEADER + constant("FR_EXCLUSIONS", fr.exclusions) + "\n" + constant("EN_EXCLUSIONS", en.exclusions),
    "pairs.ts": HEADER + constant("FR_PAIRS", fr.pairs) + "\n" + constant("EN_PAIRS", en.pairs),
  };
  for (const [name, content] of Object.entries(files)) writeFileSync(new URL(name, DATA_DIR), content);
  const manifest = {
    version,
    selectionPolicy: SELECTION_POLICY,
    source: { name: "wordfreq", version: "3.1.1", wheelSha256: "4b1c6ecffc6198be3396d5cf871c4423ca71c907c231348d352dd54d62b97473" },
    inputs,
    outputs: Object.fromEntries(Object.entries(files).map(([name, content]) => [`packages/domain/src/words/data/${name}`, sha256(content)])),
    counts: { fr: fr.counts, en: en.counts },
  };
  writeFileSync(new URL("manifest.json", reviewDir), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(JSON.stringify(manifest.counts, null, 2));
}

const usage = "select:data --raw-dir <raw> --version <version>";
try {
  const args = process.argv.slice(2);
  if (args.length !== 4 || args[0] !== "--raw-dir" || args[2] !== "--version" || !/^[a-z0-9][a-z0-9.-]{0,31}$/.test(args[3] ?? "")) throw new Error(usage);
  run(join(args[1] ?? ""), args[3] ?? "");
} catch (error: unknown) {
  console.error(error instanceof Error ? error.message : "Selection failed");
  process.exitCode = 1;
}
